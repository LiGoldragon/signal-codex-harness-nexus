#[rustfmt::skip]
#[allow(clippy::large_enum_variant)]
pub enum Answer {
    Once(Output),
    Subscribed(signal::Stream<Observations, Changed>),
}
#[rustfmt::skip]
#[allow(clippy::result_large_err, clippy::ptr_arg, clippy::borrowed_box)]
pub trait Answering {
    fn report(&self, hook: &Hook) -> std::result::Result<(), Output>;
    fn subscribe(
        &self,
    ) -> std::result::Result<signal::Stream<Observations, Changed>, Output>;
}
#[rustfmt::skip]
pub trait Answerable {
    type Answer;
    fn answer<Nexus: Answering>(&self, nexus: &Nexus) -> Self::Answer;
}
#[rustfmt::skip]
impl Answerable for Input {
    type Answer = Answer;
    fn answer<Nexus: Answering>(&self, nexus: &Nexus) -> Answer {
        match self {
            Input::Report(carried) => {
                Answer::Once(
                    nexus
                        .report(carried)
                        .map_or_else(|refusal| refusal, |()| Output::Reported),
                )
            }
            Input::Subscribe => {
                nexus.subscribe().map_or_else(Answer::Once, Answer::Subscribed)
            }
        }
    }
}
